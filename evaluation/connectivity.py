"""Tanner-graph connectivity / direct-sum decomposition audit.

A CSS or non-CSS stabilizer code's Tanner graph can split into more than
one connected component. When it does, the reported ``[[n,k,d]]`` code is
a *direct sum* of ``m`` structurally independent sub-codes glued together
-- not one genuinely new, larger, connected construction. FOM=k*d^2/n is
invariant under m-fold direct-sum replication (n->mn, k->mk, d unchanged),
so a disconnected code reports a numerically "correct" FOM while inflating
the displayed n and k relative to the smallest code that actually achieves
that FOM.

This module generalizes the ad hoc BFS check in
``tests/verify_decomposition_288_24_12.py`` into a reusable API, built on
top of the Tanner-graph construction already validated in
``evaluation.tanner_equivalence`` (including its non-CSS "tying edge",
required for correctness per CLAUDE.md) rather than re-implementing graph
construction.

Public API
----------
``bicycle_translation_component_count(ell, m, A, B, C=None, D=None)``
    Cheap, construction-free count of the translation components forced by
    a BB/PBB polynomial presentation.  This is suitable as an early campaign
    gate before rank or distance work.
``bicycle_translation_is_connected(ell, m, A, B, C=None, D=None)``
    Boolean convenience wrapper around the component count.
``tanner_components(code)``
    Connected components of the supplied generator matrix's Tanner graph.
    A split proves a code decomposition, but a connected presentation alone
    does not prove indecomposability because stabilizer row operations can
    hide a block structure.
``stabilizer_components(code)``
    Generator-basis-invariant direct-sum components of the stabilizer row
    space, as lists of qubit indices.  This is the decomposition used by
    :func:`decompose`.
``decompose(code, d=None)``
    Structural summary: component count/sizes, base ``(n0,k0,d0)`` when
    the component sizes and dimensions are homogeneous, and a per-component
    dimension cross-check.
``components_isomorphic(code)``
    Rigorous pairwise isomorphism check via BLISS canonical hashing
    (reusing ``tanner_equivalence.canonical_hash`` /
    ``canonical_hash_noncss``) on the induced sub-code of each component.
    Equal component sizes/dimensions are necessary but not sufficient for
    isomorphism; use this for a definitive answer on any specific code.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
import operator

import numpy as np

from evaluation.pbb_code import _gf2_rref
from evaluation.tanner_equivalence import (
    _extract_check_matrices,
    _extract_symplectic_matrix,
    _require_igraph,
    build_colored_tanner_graph,
    build_colored_tanner_graph_noncss,
    canonical_hash,
    canonical_hash_noncss,
    canonical_signature_digest,
)


def _is_css(code) -> bool:
    return hasattr(code, "matrix_x") and hasattr(code, "matrix_z")


def _gf2_rank(mat: np.ndarray) -> int:
    if mat.size == 0:
        return 0
    return len(_gf2_rref(mat)[1])


def _validated_support(
    ell: int, m: int, terms, name: str
) -> set[tuple[int, int]]:
    """Return a validated exponent support for the translation gate.

    Campaign evaluators already validate terms before calling the gate, but
    keeping this public helper's boundary strict prevents a malformed or
    aliased exponent from being silently reduced modulo the lattice here.
    """
    support: set[tuple[int, int]] = set()
    for term in () if terms is None else terms:
        try:
            x_raw, y_raw = term
        except (TypeError, ValueError) as exc:
            raise ValueError(f"{name} terms must be exponent pairs") from exc
        try:
            x_exp = operator.index(x_raw)
            y_exp = operator.index(y_raw)
        except TypeError as exc:
            raise ValueError(f"{name} exponents must be integers") from exc
        if not (0 <= x_exp < ell) or not (0 <= y_exp < m):
            raise ValueError(
                f"{name} exponent ({x_exp}, {y_exp}) is outside "
                f"Z_{ell} x Z_{m}"
            )
        # Over GF(2) a repeated monomial cancels rather than merely
        # coinciding, so silently deduplicating via set-membership would
        # misrepresent the polynomial. Reject instead of guessing.
        if (x_exp, y_exp) in support:
            raise ValueError(f"{name} terms contain a repeated monomial ({x_exp}, {y_exp})")
        support.add((x_exp, y_exp))
    return support


def bicycle_translation_component_count(
    ell: int,
    m: int,
    A_terms,
    B_terms,
    C_terms=None,
    D_terms=None,
) -> int:
    """Count translation components forced by a BB/PBB presentation.

    Let ``G = Z_ell x Z_m``.  For CSS BB codes, the component containing a
    check at the identity is the subgroup generated by differences within
    ``supp(A)`` and within ``supp(B)``.  Hence the number of components is
    the index of that subgroup in ``G``.  For the PBB convention used in
    :mod:`evaluation.pbb_code`, the corresponding supports are
    ``supp(A) union supp(C)`` and ``supp(B) union supp(D)``.

    The index is the second determinantal divisor of the integer matrix whose
    columns are ``(ell, 0)``, ``(0, m)``, and the support-difference
    generators: equivalently, the gcd of all its 2-by-2 minors.  This is the
    Smith-normal-form formula for
    ``[Z^2 : <(ell,0),(0,m),differences>]``.  It costs ``O(w^2)`` for row
    weight ``w``, independent of lattice area, so it is safe to apply before
    campaign sampling caps.

    A return value greater than one is a proof of a disconnected
    presentation.  As with :func:`tanner_components`, a return value of one
    does not rule out a decomposition hidden by stabilizer row operations;
    post-hoc certification should still use :func:`stabilizer_components`.

    Terms must already be reduced into the lattice's fundamental exponent
    ranges.  Invalid dimensions or exponents raise ``ValueError`` so a
    campaign cannot accidentally pass a malformed candidate through this
    safety gate.
    """
    try:
        ell = operator.index(ell)
        m = operator.index(m)
    except TypeError as exc:
        raise ValueError("lattice dimensions must be integers") from exc
    if ell <= 0 or m <= 0:
        raise ValueError("lattice dimensions must be positive")

    support_a = _validated_support(ell, m, A_terms, "A")
    support_b = _validated_support(ell, m, B_terms, "B")
    support_c = _validated_support(ell, m, C_terms, "C")
    support_d = _validated_support(ell, m, D_terms, "D")
    support_families = (support_a | support_c, support_b | support_d)
    if not support_families[0] or not support_families[1]:
        # An empty A/C or B/D family severs the only edges linking the L
        # and R qubit sectors (H_X=[A|B], H_Z=[B^T|A^T]): each sector then
        # splits into its own copy of the *other* family's orbit structure,
        # doubling the true component count in a way this single
        # subgroup-index formula cannot see. Reject rather than
        # silently under-report.
        raise ValueError(
            "translation connectivity requires nonempty A/C and B/D supports"
        )

    generators: set[tuple[int, int]] = set()
    for support in support_families:
        if not support:
            continue
        anchor_x, anchor_y = min(support)
        generators.update(
            (x_exp - anchor_x, y_exp - anchor_y)
            for x_exp, y_exp in support
        )
    generators.discard((0, 0))

    columns = [(ell, 0), (0, m), *sorted(generators)]
    component_count = 0
    for index, (x_left, y_left) in enumerate(columns):
        for x_right, y_right in columns[index + 1:]:
            determinant = x_left * y_right - y_left * x_right
            component_count = math.gcd(component_count, abs(determinant))

    # The lattice columns contribute the nonzero minor ell*m, so this cannot
    # remain zero for valid positive dimensions.
    return component_count


def bicycle_translation_is_connected(
    ell: int,
    m: int,
    A_terms,
    B_terms,
    C_terms=None,
    D_terms=None,
) -> bool:
    """Return whether the BB/PBB translation presentation is connected."""
    return (
        bicycle_translation_component_count(
            ell, m, A_terms, B_terms, C_terms, D_terms
        )
        == 1
    )


def tanner_components(code) -> list[list[int]]:
    """Components of the supplied presentation's Tanner graph.

    Dispatches on whether ``code`` is CSS (has ``matrix_x``/``matrix_z``)
    or non-CSS (``matrix`` only), reusing the exact graph construction
    ``evaluation.tanner_equivalence`` uses for permutation-equivalence
    (so the non-CSS tying edge is always present). Components are sorted
    by their smallest qubit index; each component's qubit list is sorted
    ascending. A component with zero qubits (an isolated all-zero check
    row, which shouldn't occur for a valid stabilizer generator) is
    dropped rather than reported.
    """
    n = code.num_qudits
    if _is_css(code):
        g, _colors = build_colored_tanner_graph(code)
    else:
        g, _colors = build_colored_tanner_graph_noncss(code)

    components = []
    for cluster in g.connected_components():
        qubits = sorted(v for v in cluster if v < n)
        if qubits:
            components.append(qubits)
    components.sort(key=lambda c: c[0])
    return components


def _stabilizer_basis(code) -> np.ndarray:
    """Return the unique RREF basis of the binary stabilizer row space."""
    if _is_css(code):
        H_X, H_Z = _extract_check_matrices(code)
        n = H_X.shape[1]
        zero_x = np.zeros((H_X.shape[0], n), dtype=int)
        zero_z = np.zeros((H_Z.shape[0], n), dtype=int)
        symplectic = np.vstack(
            [np.hstack([H_X, zero_x]), np.hstack([zero_z, H_Z])]
        )
    else:
        symplectic = _extract_symplectic_matrix(code)
    rref, pivots = _gf2_rref(symplectic)
    return rref[: len(pivots)]


def _components_from_basis(basis: np.ndarray, n: int) -> list[list[int]]:
    """Return qubit components from an already reduced stabilizer basis."""
    parent = list(range(n))

    def find(item: int) -> int:
        while parent[item] != item:
            parent[item] = parent[parent[item]]
            item = parent[item]
        return item

    def union(left: int, right: int) -> None:
        root_left, root_right = find(left), find(right)
        if root_left != root_right:
            parent[root_right] = root_left

    for row in basis:
        support = np.flatnonzero((row[:n] != 0) | (row[n:] != 0))
        if support.size > 1:
            first = int(support[0])
            for qubit in support[1:]:
                union(first, int(qubit))

    groups: dict[int, list[int]] = {}
    for qubit in range(n):
        groups.setdefault(find(qubit), []).append(qubit)
    return sorted((sorted(group) for group in groups.values()), key=lambda c: c[0])


def stabilizer_components(code) -> list[list[int]]:
    """Return the finest qubit partition of the stabilizer row space.

    The computation row-reduces the full binary symplectic stabilizer matrix
    and joins qubits that occur in a common row of its unique RREF basis.
    X and Z coordinates belonging to one physical qubit are treated as one
    coordinate block.  Unlike connectivity of a supplied generator matrix,
    this partition is invariant under stabilizer row operations.
    """
    return _components_from_basis(_stabilizer_basis(code), int(code.num_qudits))


def _component_dimension(
    code, qubit_indices: list[int], *, basis: np.ndarray | None = None
) -> int:
    """GF(2) dimension ``k_component = n_component - rank`` of the sub-code
    induced on ``qubit_indices``.

    Uses a single symplectic-rank formula that is correct for both CSS
    and non-CSS: stack every check row whose full support lies entirely
    within ``qubit_indices`` (by the connected-component property, any
    row touching one qubit in the component touches only qubits in that
    component), restricted to those columns, and take
    ``len(qubit_indices) - rank([X-part | Z-part])``. For CSS this is
    exactly the standard ``n - rank(H_X) - rank(H_Z)`` (the X-rows and
    Z-rows have disjoint nonzero blocks, so the stacked rank is additive).
    """
    idx = np.array(qubit_indices)
    component_n = len(idx)
    full_n = int(code.num_qudits)
    mask_cols = np.zeros(full_n, dtype=bool)
    mask_cols[idx] = True
    if basis is None:
        basis = _stabilizer_basis(code)
    support = (basis[:, :full_n] != 0) | (basis[:, full_n:] != 0)
    keep = support.any(axis=1) & ~(support & ~mask_cols).any(axis=1)
    restricted = np.hstack([basis[keep][:, idx], basis[keep][:, full_n + idx]])
    return component_n - _gf2_rank(restricted)


@dataclass
class DecompositionResult:
    n_components: int
    component_sizes: list[int]
    is_connected: bool
    homogeneous: bool
    component_k: list[int] | None
    k_additivity_ok: bool | None
    base_n: int | None
    base_k: int | None
    base_d: int | None
    presentation_agrees: bool


def decompose(code, d: int | None = None) -> DecompositionResult:
    """Structural decomposition summary for ``code``.

    ``base_n`` is populated when the component sizes are homogeneous;
    ``base_k`` and ``base_d`` additionally require equal component
    dimensions.  These conditions are necessary, not sufficient, for the
    components to be isomorphic copies of one base code -- use
    :func:`components_isomorphic` for a definitive per-code answer when the
    stored and invariant partitions agree.
    ``base_d`` is simply the passed-through ``d``: the distance of a
    direct sum of isomorphic components equals the (shared) component
    distance, which is what the caller has already certified for the
    whole code.
    """
    basis = _stabilizer_basis(code)
    components = _components_from_basis(basis, int(code.num_qudits))
    presentation_agrees = components == tanner_components(code)
    n_components = len(components)
    component_sizes = [len(c) for c in components]
    is_connected = n_components <= 1
    homogeneous = len(set(component_sizes)) <= 1

    component_k = None
    k_additivity_ok = None
    if n_components > 1:
        component_k = [
            _component_dimension(code, component, basis=basis)
            for component in components
        ]
        k_additivity_ok = sum(component_k) == code.dimension

    base_n = base_k = base_d = None
    if not is_connected and homogeneous:
        base_n = code.num_qudits // n_components
        if component_k is not None and len(set(component_k)) == 1:
            base_k = component_k[0]
            # Equal (n, k) alone does not prove the components share a
            # distance -- a direct sum's distance is min(d_i), and
            # differently-shaped components can coincidentally match n
            # and k while having different d_i. Only claim a shared base
            # distance once components_isomorphic() actually proves the
            # components are the same code.
            if components_isomorphic(code):
                base_d = d

    return DecompositionResult(
        n_components=n_components,
        component_sizes=component_sizes,
        is_connected=is_connected,
        homogeneous=homogeneous,
        component_k=component_k,
        k_additivity_ok=k_additivity_ok,
        base_n=base_n,
        base_k=base_k,
        base_d=base_d,
        presentation_agrees=presentation_agrees,
    )


class _InducedCSSCode:
    """Minimal ``matrix_x``/``matrix_z`` duck-type accepted by
    ``tanner_equivalence.build_colored_tanner_graph``."""

    __slots__ = ("matrix_x", "matrix_z")

    def __init__(self, matrix_x: np.ndarray, matrix_z: np.ndarray):
        self.matrix_x = matrix_x
        self.matrix_z = matrix_z


class _InducedNonCSSCode:
    """Minimal ``matrix`` duck-type accepted by
    ``tanner_equivalence.build_colored_tanner_graph_noncss``."""

    __slots__ = ("matrix",)

    def __init__(self, matrix: np.ndarray):
        self.matrix = matrix


def _induced_rowspace_subcode(code, qubit_indices: list[int]):
    """Build an induced sub-code from the canonical stabilizer RREF basis."""
    idx = np.array(qubit_indices)
    full_n = int(code.num_qudits)
    mask_cols = np.zeros(full_n, dtype=bool)
    mask_cols[idx] = True
    basis = _stabilizer_basis(code)
    support = (basis[:, :full_n] != 0) | (basis[:, full_n:] != 0)
    keep = support.any(axis=1) & ~(support & ~mask_cols).any(axis=1)
    restricted_x = basis[keep][:, idx]
    restricted_z = basis[keep][:, full_n + idx]

    if _is_css(code):
        has_x = (restricted_x != 0).any(axis=1)
        has_z = (restricted_z != 0).any(axis=1)
        if np.any(has_x & has_z):
            raise ValueError("RREF of a CSS stabilizer unexpectedly contains mixed rows")
        return _InducedCSSCode(restricted_x[has_x], restricted_z[has_z])
    return _InducedNonCSSCode(np.hstack([restricted_x, restricted_z]))


def _induced_presentation_subcode(code, qubit_indices: list[int]):
    """Restrict the supplied generator presentation to one component."""
    idx = np.array(qubit_indices)
    full_n = int(code.num_qudits)
    mask_cols = np.zeros(full_n, dtype=bool)
    mask_cols[idx] = True

    if _is_css(code):
        H_X, H_Z = _extract_check_matrices(code)
        keep_x = (H_X != 0).any(axis=1) & ~((H_X != 0) & ~mask_cols).any(axis=1)
        keep_z = (H_Z != 0).any(axis=1) & ~((H_Z != 0) & ~mask_cols).any(axis=1)
        return _InducedCSSCode(H_X[keep_x][:, idx], H_Z[keep_z][:, idx])

    H = _extract_symplectic_matrix(code)
    H_X, H_Z = H[:, :full_n], H[:, full_n:]
    support = (H_X != 0) | (H_Z != 0)
    keep = support.any(axis=1) & ~(support & ~mask_cols).any(axis=1)
    return _InducedNonCSSCode(np.hstack([H_X[keep][:, idx], H_Z[keep][:, idx]]))


def components_isomorphic(code) -> bool | None:
    """Check presentation isomorphism across direct-sum components of ``code``.

    The comparison uses BLISS canonical hashing of each induced sub-code.

    Returns ``True`` for a connected code, or when any comparison below
    finds matching canonical hashes -- equal colored-Tanner-graph hashes
    are always a sound proof of isomorphism. Unequal hashes are never
    treated as a disproof and instead return ``None`` (inconclusive):
    two row-equivalent but differently-chosen generating sets for the
    same code can induce different Tanner graphs, so an unequal hash
    only proves the compared presentations differ, not that the
    underlying component codes are non-isomorphic. The RREF basis
    checked below is invariant under row operations but, like any
    presentation, is not permutation-equivariant, so it cannot supply a
    definitive negative either.
    """
    _require_igraph()
    components = stabilizer_components(code)
    if len(components) <= 1:
        return True

    hash_fn = canonical_hash if _is_css(code) else canonical_hash_noncss
    # Prefer the supplied presentation when its Tanner partition agrees
    # with the invariant row-space partition -- this is a cheap equality
    # fast path only; see the docstring for why inequality here is not
    # acted on.
    presentation_agrees = components == tanner_components(code)
    if presentation_agrees:
        presentation_hashes = [
            hash_fn(_induced_presentation_subcode(code, component))
            for component in components
        ]
        if len(set(presentation_hashes)) == 1:
            return True

    rowspace_hashes = [
        hash_fn(_induced_rowspace_subcode(code, component)) for component in components
    ]
    isomorphic = len(set(rowspace_hashes)) == 1
    return True if isomorphic else None


def component_canonical_digest(code) -> str:
    """Return a stable canonical digest for one connected component.

    The digest is computed from the stored-generator presentation restricted
    to a component of the invariant stabilizer-row-space partition.  It is
    therefore suitable for comparing components of parents with different
    replication multiplicities.  The helper is deliberately strict: it
    requires the stored-generator and invariant partitions to agree and all
    components to have the same colored-Tanner canonical form.
    """
    _require_igraph()
    components = stabilizer_components(code)
    if components != tanner_components(code):
        raise ValueError(
            "component canonicalization requires the stored-generator and "
            "stabilizer-row-space partitions to agree"
        )

    hash_fn = canonical_hash if _is_css(code) else canonical_hash_noncss
    signatures = [
        hash_fn(_induced_presentation_subcode(code, component))
        for component in components
    ]
    if len(set(signatures)) != 1:
        raise ValueError("component presentations are not pairwise isomorphic")
    return canonical_signature_digest(signatures[0])
