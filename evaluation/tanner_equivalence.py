"""Stored-generator permutation equivalence via BLISS canonical labeling.

Given two CSS stabilizer codes specified by parity-check matrices
``(H_X, H_Z)`` and ``(H_X', H_Z')`` over ``n`` qubits, this module
decides whether they are *permutation-equivalent*, i.e., whether there
exists a qubit permutation ``π`` and row permutations ``σ_X``, ``σ_Z``
satisfying

    σ_X · H_X · π = H_X',   σ_Z · H_Z · π = H_Z'    (mod 2),

where ``π`` acts on columns (qubits) and ``σ_X``, ``σ_Z`` act on rows
(X-stabilizer generators, Z-stabilizer generators) independently.

Algorithm
---------
Build a colored Tanner graph with three vertex colors:

* color 0 -- qubit vertices (``n`` total)
* color 1 -- X-stabilizer-check vertices (``rx`` total)
* color 2 -- Z-stabilizer-check vertices (``rz`` total)

Edges connect each qubit to the checks it appears in.  Apply BLISS
canonical labeling that respects the three-color partition (igraph's
``canonical_permutation(color=...)``).  Two codes are permutation-
equivalent iff their canonical forms agree.

Correctness (biconditional)
---------------------------
* ``(⇒)`` If ``π``, ``σ_X``, ``σ_Z`` realise the equivalence, the
  bijection ``φ`` on graph vertices defined by
  ``φ(qubit j) = qubit π(j)``, ``φ(X-check r) = X-check σ_X(r)``,
  ``φ(Z-check r) = Z-check σ_Z(r)`` preserves the colored edge
  incidences (``H_X[r, j] = H_X'[σ_X(r), π(j)]`` etc.), so ``φ`` is a
  colored graph isomorphism.
* ``(⇐)`` Conversely, any colored graph isomorphism ``φ`` restricts to
  a bijection ``π`` on the qubit color class.  Color preservation
  forces ``φ`` to map X-check vertices to X-check vertices and Z-check
  vertices to Z-check vertices; together with edge preservation this
  gives row permutations ``σ_X``, ``σ_Z`` realising the equivalence.

BLISS guarantees that two graphs are isomorphic iff their canonical
forms agree, so equality of the canonical hashes returned by
``canonical_hash`` is sound and complete for permutation equivalence.

Scope and caveats
-----------------
* "Permutation equivalence" here is the relation generated by qubit
  relabeling.  X-stabilizer rows may permute among themselves and
  Z-stabilizer rows may permute among themselves; X and Z roles are
  **not** exchangeable.

* The decision is on the **stabilizer matrix as given**, not the
  stabilizer **group**.  Two CSS codes whose ``H_X``, ``H_Z`` arise
  from different generating sets of the same stabilizer subgroup may
  have different canonical hashes.  This conservative distinction is
  deliberate in a stored-presentation audit.

* The decision does **not** cover broader equivalence relations:

  - Hadamard equivalence (X-stabilizers swapped with Z-stabilizers)
    would require dropping the color distinction between colors 1 and
    2.
  - Local Clifford equivalence (per-qubit ``S``, ``H``, etc.) is a
    strictly coarser relation; see ``evaluation/clifford_equivalence``
    for sufficient checks.
  - General code equivalence (any unitary intertwining the two
    stabilizer groups) is coarser still and not addressed here.

* The default API is for **CSS** codes presented as ``H_X, H_Z``.  The
  ``*_noncss`` API implements the analogous stored-generator relation
  for a symplectic matrix whose rows mix X and Z: each row's two support
  vertices are tied by an edge so their row permutation cannot decouple.
  Neither API quotients arbitrary stabilizer-basis changes.

Public API
----------
``build_colored_tanner_graph(code)``
    Construct the 3-colored Tanner graph from a qldpc CSS code object.
``canonical_hash(code)``
    Hashable canonical representative; equal hashes iff
    permutation-equivalent.
``canonical_digest(code)``
    Stable SHA-256 serialization of ``canonical_hash`` for persisted class
    identifiers and audit sidecars.
``canonical_signature_digest(signature)``
    Stable SHA-256 serialization of an already computed canonical signature.
``are_permutation_equivalent(code_a, code_b)``
    Convenience boolean wrapper around ``canonical_hash``.
``extract_qubit_permutation(code_a, code_b)``
    Return the qubit permutation realising the equivalence, or
    ``None`` if the codes are not permutation-equivalent.
``extract_full_vertex_isomorphism(code_a, code_b)``
    Return the full graph-vertex isomorphism (qubits + X-checks +
    Z-checks) realising the equivalence, or ``None`` if the codes are
    not permutation-equivalent.  Useful when callers need the X-check
    and Z-check row permutations as well as the qubit permutation.
``build_colored_tanner_graph_noncss(code)``
    Non-CSS variant: 3-coloring with each stabilizer split into an
    X-support vertex (color 1) and a Z-support vertex (color 2),
    tied by an edge so BLISS's color-respecting canonicalisation
    decides exactly stabilizer permutation equivalence.  See the
    "Non-CSS extension" comment block below for the construction and
    its motivation.
``canonical_hash_noncss(code)``
    Hashable canonical form of a non-CSS stabilizer code under
    stabilizer permutation equivalence.
``canonical_digest_noncss(code)``
    Stable SHA-256 serialization of ``canonical_hash_noncss``.
``are_permutation_equivalent_noncss(code_a, code_b)``
    Boolean wrapper around ``canonical_hash_noncss``.

Dependency note
---------------
This module imports ``igraph`` lazily because ``python-igraph`` is in
the project's ``dev`` dependency group, not the core install (see
``CLAUDE.md``); calling any function here without ``python-igraph``
installed raises a clear ``ImportError`` rather than a NameError at
import time.
"""

from __future__ import annotations

import hashlib
import struct

import numpy as np


def _require_igraph():
    """Lazy import of igraph with a clear error message."""
    try:
        import igraph as ig
    except ImportError as exc:
        raise ImportError(
            "evaluation.tanner_equivalence requires python-igraph. "
            "Install with: uv add --group dev python-igraph"
        ) from exc
    return ig


def _extract_check_matrices(code):
    """Return (H_X, H_Z) as dense binary numpy arrays from a CSS code."""
    H_X = np.array(
        code.matrix_x.toarray() if hasattr(code.matrix_x, "toarray") else code.matrix_x,
        dtype=int,
    ) % 2
    H_Z = np.array(
        code.matrix_z.toarray() if hasattr(code.matrix_z, "toarray") else code.matrix_z,
        dtype=int,
    ) % 2
    if H_X.ndim != 2 or H_Z.ndim != 2:
        raise ValueError("CSS check matrices must both be two-dimensional")
    if H_X.shape[1] != H_Z.shape[1]:
        raise ValueError(
            "CSS check matrices must have the same number of qubit columns"
        )
    return H_X, H_Z


def build_colored_tanner_graph(code):
    """Build the 3-colored Tanner graph used by the equivalence decision.

    Vertices are partitioned by color:

    * color 0: qubits (``n`` vertices), indices ``[0, n)``
    * color 1: X-stabilizer checks (``rx`` vertices), indices ``[n, n+rx)``
    * color 2: Z-stabilizer checks (``rz`` vertices), indices ``[n+rx, n+rx+rz)``

    Edges connect each qubit to the checks it appears in.  No edges
    run between two checks; X-checks and Z-checks are not
    interconnected.

    Returns
    -------
    (graph, colors): tuple
        ``graph`` is an ``igraph.Graph`` and ``colors`` is the list
        passed to BLISS for color-respecting canonicalisation.
    """
    ig = _require_igraph()
    H_X, H_Z = _extract_check_matrices(code)
    n = H_X.shape[1]
    rx, rz = H_X.shape[0], H_Z.shape[0]

    g = ig.Graph(n + rx + rz, directed=False)
    colors = [0] * n + [1] * rx + [2] * rz

    edges = []
    for r in range(rx):
        for j in range(n):
            if H_X[r, j] == 1:
                edges.append((j, n + r))
    for r in range(rz):
        for j in range(n):
            if H_Z[r, j] == 1:
                edges.append((j, n + rx + r))
    g.add_edges(edges)

    return g, colors


def _canonical_colored_form(graph, colors):
    """Return a color-aware canonical signature and vertex permutation.

    A color-aware canonical permutation is not enough if the returned
    signature drops the colors: differently colored versions of the same
    uncolored graph can otherwise collide.
    """
    graph.vs["_canonical_color"] = list(colors)
    permutation = graph.canonical_permutation(color=colors)
    canonical = graph.permute_vertices(permutation)
    signature = (
        tuple(canonical.vs["_canonical_color"]),
        tuple(sorted(canonical.get_edgelist())),
    )
    return signature, permutation


def _canonical_colored_signature(graph, colors):
    """Return a canonical signature that retains vertex colors."""
    signature, _ = _canonical_colored_form(graph, colors)
    return signature


def canonical_signature_digest(signature) -> str:
    """Return a stable SHA-256 digest of a colored canonical signature."""
    colors, edges = signature
    digest = hashlib.sha256()
    digest.update(struct.pack(">Q", len(colors)))
    for color in colors:
        digest.update(struct.pack(">q", int(color)))
    digest.update(struct.pack(">Q", len(edges)))
    for left, right in edges:
        digest.update(struct.pack(">qq", int(left), int(right)))
    return digest.hexdigest()


def canonical_hash(code):
    """Hashable canonical representative of a CSS code under permutation
    equivalence.

    Two CSS codes return equal canonical hashes iff they are
    permutation-equivalent (qubit relabel preserving X-stabilizer and
    Z-stabilizer roles); see the module docstring for the proof.

    The hash contains the canonicalized color sequence and edge list and is
    suitable as a dict key.
    """
    g, c = build_colored_tanner_graph(code)
    return _canonical_colored_signature(g, c)


def canonical_digest(code) -> str:
    """Stable digest of :func:`canonical_hash`, suitable for sidecars."""
    return canonical_signature_digest(canonical_hash(code))


def are_permutation_equivalent(code_a, code_b) -> bool:
    """Return True iff ``code_a`` and ``code_b`` are permutation-equivalent.

    See the module docstring for the precise definition and the
    biconditional proof.
    """
    return canonical_hash(code_a) == canonical_hash(code_b)


def extract_full_vertex_isomorphism(code_a, code_b):
    """Return the full graph-vertex isomorphism mapping ``code_a`` to
    ``code_b``, or ``None`` if the codes are not permutation-equivalent.

    Returns a list of length ``n + rx + rz`` giving the index in
    ``code_b``'s Tanner graph of each vertex of ``code_a``'s Tanner
    graph (vertex layout is qubits, then X-checks, then Z-checks; see
    ``build_colored_tanner_graph``).  Slice the first ``n`` entries
    for the qubit permutation, the next ``rx`` for the X-check row
    permutation, and the final ``rz`` for the Z-check row permutation.
    """
    g_a, c_a = build_colored_tanner_graph(code_a)
    g_b, c_b = build_colored_tanner_graph(code_b)

    signature_a, perm_a = _canonical_colored_form(g_a, c_a)
    signature_b, perm_b = _canonical_colored_form(g_b, c_b)
    if signature_a != signature_b:
        return None

    inv_perm_a = [0] * len(perm_a)
    for k, v in enumerate(perm_a):
        inv_perm_a[v] = k
    return [perm_b[inv_perm_a[i]] for i in range(len(perm_a))]


def extract_qubit_permutation(code_a, code_b):
    """Return the qubit permutation mapping ``code_a`` to ``code_b``,
    or ``None`` if the codes are not permutation-equivalent.

    Returns a list ``qubit_perm`` of length ``n`` such that qubit ``j``
    of ``code_a`` corresponds to qubit ``qubit_perm[j]`` of ``code_b``
    (under some compatible row reorderings of the X and Z stabilizer
    matrices).  Use any caller-side helper such as
    ``analyze_qubit_permutation`` (in ``tests/check_code_equivalence``)
    to interpret the result in lattice ``(ℓ, m)`` coordinates.

    For the X-check and Z-check row permutations as well, use
    ``extract_full_vertex_isomorphism``.
    """
    full = extract_full_vertex_isomorphism(code_a, code_b)
    if full is None:
        return None
    n = _extract_check_matrices(code_a)[0].shape[1]
    return full[:n]


# ---------------------------------------------------------------------------
# Non-CSS extension
#
# For non-CSS stabilizer codes (full symplectic matrix; each stabilizer mixes
# X and Z support), the colored Tanner graph is generalised to use *three*
# vertex colors with each stabilizer represented by a pair of check vertices:
#
#   color 0: qubits                                (n vertices)
#   color 1: X-support vertex of each stabilizer   (n_checks vertices)
#   color 2: Z-support vertex of each stabilizer   (n_checks vertices)
#
# Edges:
#   qubit i -> X-support j        iff  stabilizer j has X-action on qubit i
#   qubit i -> Z-support j        iff  stabilizer j has Z-action on qubit i
#   X-support j -> Z-support j    for every stabilizer j  (CRITICAL)
#
# The third edge type — tying the X-support and Z-support of each stabilizer —
# is essential.  Without it, BLISS's color-respecting canonical permutation is
# free to permute X-support vertices independently of Z-support vertices
# (sigma_X != sigma_Z), decoupling the (X, Z) pair of each stabilizer.  No
# qubit permutation realises such a decoupling, so the relation BLISS would
# decide without the tying edge would be *strictly broader* than stabilizer
# permutation equivalence — it would merge codes whose X- and Z-incidence
# hypergraphs are independently isomorphic but whose joint generator structure
# differs (including codes with mismatched generator weights and distances).
# The implementation below always adds the tying edges, so the canonical hash
# is sound and complete for stabilizer permutation equivalence.
# ---------------------------------------------------------------------------


def _extract_symplectic_matrix(code):
    """Return the symplectic stabilizer matrix as a dense binary numpy array.

    For a non-CSS qldpc ``QuditCode``, returns the (num_stabs, 2*n) matrix
    ``code.matrix`` reduced mod 2.  Splits into (H_X, H_Z) for the caller.
    """
    H = np.array(
        code.matrix.toarray() if hasattr(code.matrix, "toarray") else code.matrix,
        dtype=int,
    ) % 2
    if H.ndim != 2:
        raise ValueError("the symplectic check matrix must be two-dimensional")
    if H.shape[1] % 2:
        raise ValueError(
            "the symplectic check matrix must have an even number of columns"
        )
    return H


def build_colored_tanner_graph_noncss(code):
    """Build the colored Tanner graph for a non-CSS stabilizer code.

    See the "Non-CSS extension" comment block above for the construction;
    in particular, the X-support and Z-support of each stabilizer are tied
    by an edge so that BLISS decides exactly stabilizer permutation
    equivalence (sound + complete).

    Returns
    -------
    (graph, colors): tuple
        ``graph`` is an ``igraph.Graph`` and ``colors`` is the list passed
        to BLISS for color-respecting canonicalisation.
    """
    ig = _require_igraph()
    H = _extract_symplectic_matrix(code)
    n_checks, two_n = H.shape
    n = two_n // 2
    H_X, H_Z = H[:, :n], H[:, n:]

    g = ig.Graph(n + 2 * n_checks, directed=False)
    colors = [0] * n + [1] * n_checks + [2] * n_checks
    edges = []
    for j in range(n_checks):
        for i in range(n):
            if H_X[j, i] == 1:
                edges.append((i, n + j))
            if H_Z[j, i] == 1:
                edges.append((i, n + n_checks + j))
        # X-support j <-> Z-support j (tying edge; see comment block above)
        edges.append((n + j, n + n_checks + j))
    g.add_edges(edges)
    return g, colors


def canonical_hash_noncss(code):
    """Hashable canonical representative of a non-CSS stabilizer code under
    stabilizer permutation equivalence.

    Two non-CSS codes return equal canonical hashes iff they are related
    by a qubit permutation paired with a tied row permutation of the
    symplectic stabilizer matrix; see the "Non-CSS extension" comment
    block.  The hash contains the canonicalized color sequence and edge list
    of the BLISS-canonicalised colored Tanner graph (with X-support/Z-support
    tying edges) and is suitable as a dict key.
    """
    g, c = build_colored_tanner_graph_noncss(code)
    return _canonical_colored_signature(g, c)


def canonical_digest_noncss(code) -> str:
    """Stable digest of :func:`canonical_hash_noncss`."""
    return canonical_signature_digest(canonical_hash_noncss(code))


def are_permutation_equivalent_noncss(code_a, code_b) -> bool:
    """Return True iff ``code_a`` and ``code_b`` are stabilizer
    permutation-equivalent under the non-CSS coloring."""
    return canonical_hash_noncss(code_a) == canonical_hash_noncss(code_b)
